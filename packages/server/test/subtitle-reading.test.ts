interface Answer {
  status: number;
  ms: number;
  cues: Array<{ start: number; end: number; text: string; top?: boolean; italic?: boolean }>;
  complete?: boolean;
  covered?: Array<[number, number | null]>;
  sig?: string;
  unchanged?: boolean;
  from?: number;
  to?: number;
}
async function ask(id: number, rk: string, at?: number, since?: string): Promise<Answer> {
  const q = new URLSearchParams({ ratingKey: rk });
  if (at !== undefined) q.set("at", String(at));
  if (since) q.set("since", since);
  const began = Date.now();
  const r = await fetch(`${origin}/api/plex/subtitles/${id}?${q}`);
  const body = r.ok ? await r.json() as Omit<Answer, "status" | "ms"> : { cues: [] };
  return { status: r.status, ms: Date.now() - began, ...body, cues: body.cues ?? [] };
}
const coveredAt = (a: Answer, at: number) => (a.covered ?? []).some(([f, t]) => f <= at && (t === null || at < t));
const lineAt = (a: Answer, start: number) => a.cues.find((c) => Math.abs(c.start - start) < 0.01);
const readsOf = (id: number) => reads.filter((r) => r.id === String(id));

// ── From the start ────────────────────────────────────────────────

console.log("— from the start, the lines as Plex sends them —");
{
  const first = await ask(81, "800", 0);
  check("answered within a second and a half, not when Plex is done", first.ms < 1500, true);
  check("still being read", [first.status, first.complete], [200, false]);
  check("with the first line, though Plex sends Windows line ends and no blank lines",
    lineAt(first, 20)?.text, "Line 1 of 81");
  check("and the stretch it is all there for, from the start", coveredAt(first, 0) && coveredAt(first, 25), true);
  // Playing on: what a player asks as it goes, a few times a second.
  let midway: Answer | null = null;
  const began = Date.now();
  await until(async () => {
    const a = await ask(81, "800", (Date.now() - began) / 1000);
    if (!a.complete && a.cues.length >= 20) midway = a;
    return a.complete === true;
  }, 15_000);
  check("lines keep coming while Plex reads", midway !== null, true);
  check("italics from Plex's converted text are kept", lineAt(midway!, 80)?.italic, true);
  const done = await ask(81, "800", 0);
  check("then all of them, complete", [done.complete, done.cues.length], [true, titles["800"].subs[0].lines.length]);
  check("Plex was asked to read it once, from the start", readsOf(81).map((r) => r.offset), [0]);
}

