let pass = 0;
let fail = 0;
function check(name: string, actual: unknown, expected: unknown) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) { pass++; console.log(`  ok   ${name}`); }
  else { fail++; console.log(`  FAIL ${name}\n         expected ${e}\n         actual   ${a}`); }
}
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
/** Asks `cond` until it holds, and not once more after: a `cond` that asks
 *  the server would ask again, and could be answered otherwise. */
async function until(cond: () => boolean | Promise<boolean>, ms = 10_000) {
  const end = Date.now() + ms;
  for (;;) {
    if (await cond()) return true;
    if (Date.now() >= end) return false;
    await sleep(25);
  }
}

// ── The film and its subtitles ────────────────────────────────────

const DURATION = 7200;
/** Film seconds the fake Plex reads a millisecond. */
const PACE = 1.2;

interface Sub {
  id: number;
  /** As Plex names it. */
  codec: "srt" | "ass" | "mov_text";
  lines: FixtureLine[];
  /** Plex can't read this one out. */
  fails?: boolean;
}

/** A line every ten seconds from 0:20: the srt ones with every seventh in
 *  italics, the ass ones with every fifth a sign at the top. */
function script(id: number, codec: Sub["codec"]): FixtureLine[] {
  const lines: FixtureLine[] = [];
  for (let t = 20, n = 1; t < DURATION - 10; t += 10, n++) {
    const text = `Line ${n} of ${id}`;
    if (codec === "ass") lines.push({ start: t, end: t + 4, text: `0,${n % 5 === 0 ? "Sign" : "Default"},,0,0,0,,${text}` });
    else lines.push({ start: t, end: t + 4, text: n % 7 === 0 ? `<i>${text}</i>` : text });
  }
  return lines;
}
const sub = (id: number, codec: Sub["codec"], extra: Partial<Sub> = {}): Sub => ({ id, codec, lines: script(id, codec), ...extra });

const ASS_HEADER = [
  "[Script Info]", "; Script generated by FFmpeg/Lavc60.31.102", "ScriptType: v4.00+", "PlayResX: 384", "PlayResY: 288",
  "ScaledBorderAndShadow: yes", "YCbCr Matrix: None", "",
  "[V4+ Styles]",
  "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
  "Style: Default,Arial,16,&Hffffff,&Hffffff,&H0,&H0,0,0,0,0,100,100,0,0,1,1,0,2,10,10,10,0",
  "Style: Sign,Arial,16,&Hffffff,&Hffffff,&H0,&H0,0,0,0,0,100,100,0,0,1,1,0,8,10,10,10,0",
  "",
  "[Events]",
  "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
].join("\r\n") + "\r\n";

const assTime = (s: number) => {
  const cs = Math.round(s * 100);
  return `${Math.floor(cs / 360000)}:${String(Math.floor(cs / 6000) % 60).padStart(2, "0")}:${String(Math.floor(cs / 100) % 60).padStart(2, "0")}.${String(cs % 100).padStart(2, "0")}`;
};
/** A line as Plex sends it: SRT converted to ASS, its italics turned into a
 *  tag; an ASS line as it is. */
function plexLine(s: Sub, l: FixtureLine): string {
  if (s.codec === "ass") {
    const [layer, ...rest] = l.text.split(",");
    return `Dialogue: ${layer},${assTime(l.start)},${assTime(l.end)},${rest.join(",")}\r\n`;
  }
  const italic = /^<i>(.*)<\/i>$/.exec(l.text);
  return `Dialogue: 0,${assTime(l.start)},${assTime(l.end)},Default,,0,0,0,,${italic ? `{\\i1}${italic[1]}{\\i0}` : l.text}\r\n`;
}

/** Each title: its file, and its subtitles inside it. */
interface Title { container: "mkv" | "mp4"; subs: Sub[]; file: Buffer | null }
const titles: Record<string, Title> = {};
function title(rk: string, container: Title["container"], subs: Sub[], file: Parameters<typeof matroskaWithSubtitles>[0] | null) {
  titles[rk] = { container, subs, file: file ? matroskaWithSubtitles(file) : null };
}
const mkvTracks = (subs: Sub[], zlib = false) => subs.map((s) => ({
  codec: s.codec === "ass" ? "S_TEXT/ASS" as const : "S_TEXT/UTF8" as const,
  lines: s.lines,
  ...(s.codec === "ass" ? { header: ASS_HEADER.replace(/\r\n/g, "\n") } : {}),
  ...(zlib ? { zlib } : {}),
}));
// 800: a remux whose index lists every subtitle line, and a picture subtitle.
{
  const subs = [sub(81, "srt"), sub(82, "ass")];
  title("800", "mkv", subs, { durationS: DURATION, tracks: [...mkvTracks(subs), { codec: "S_HDMV/PGS", lines: [] }] });
}
// 801: one whose index lists only the video, as ffmpeg's muxer writes it.
{
  const subs = [sub(84, "srt"), sub(85, "ass")];
  title("801", "mkv", subs, { durationS: DURATION, tracks: mkvTracks(subs), subtitleCues: false });
}
// 802: an MP4, and 806 another, started from the beginning.
title("802", "mp4", [sub(86, "mov_text")], null);
title("806", "mp4", [sub(90, "mov_text")], null);
// 803: one Plex can't read out.
{
  const subs = [sub(87, "srt", { fails: true })];
  title("803", "mkv", subs, { durationS: DURATION, tracks: mkvTracks(subs) });
}
// 804: an old remux: its subtitle packed with zlib, half its clusters' sizes
// written in eight bytes.
{
  const subs = [sub(88, "srt")];
  title("804", "mkv", subs, { durationS: DURATION, tracks: mkvTracks(subs, true), wideClusters: true });
}
// 805: for asking without saying where: the old player.
{
  const subs = [sub(89, "srt")];
  title("805", "mkv", subs, { durationS: DURATION, tracks: mkvTracks(subs) });
}
const allSubs = new Map(Object.values(titles).flatMap((t) => t.subs).map((s) => [String(s.id), s]));

// ── The fake Plex ─────────────────────────────────────────────────

/** Each item's selected subtitle, as Plex keeps it. */
const selected: Record<string, string> = {};
interface PlexRead { session: string; id: string; offset: number; stopped: boolean; done: boolean; open: boolean }
const reads: PlexRead[] = [];
const stops: string[] = [];
let partRanges = 0;

const plex = http.createServer((req, res) => {
  const url = new URL(req.url!, "http://plex");
  const send = (body: unknown) => {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ MediaContainer: body }));
  };
  const meta = url.pathname.match(/^\/library\/metadata\/(\d+)$/);
  if (meta && titles[meta[1]]) {
    const t = titles[meta[1]];
    return send({ Metadata: [{
      ratingKey: meta[1], title: "Film", type: "movie", duration: DURATION * 1000,
      Media: [{ id: 1, width: 1920, height: 1080, videoCodec: "h264", bitrate: 8000, container: t.container, Part: [{
        id: Number(meta[1]), key: `/library/parts/${meta[1]}/1/file.${t.container}`, size: t.file?.length ?? 1e9,
        container: t.container, Stream: [
          { id: 1, streamType: 1, codec: "h264", index: 0 },
          { id: 2, streamType: 2, codec: "aac", selected: true, index: 1 },
          ...t.subs.map((s, i) => ({ id: s.id, streamType: 3, codec: s.codec, language: "English", languageCode: "eng", index: 2 + i })),
          ...(meta[1] === "800" ? [{ id: 83, streamType: 3, codec: "pgs", language: "English", languageCode: "eng", index: 4 }] : []),
        ],
      }] }],
    }] });
  }
  const part = url.pathname.match(/^\/library\/parts\/(\d+)$/);
  if (part && req.method === "PUT") {
    selected[part[1]] = url.searchParams.get("subtitleStreamID") ?? selected[part[1]];
    return send({});
  }
  const file = url.pathname.match(/^\/library\/parts\/(\d+)\/1\/file\.mkv$/);
  if (file && titles[file[1]]?.file) {
    partRanges++;
    const data = titles[file[1]].file!;
    const m = /bytes=(\d+)-(\d+)/.exec(String(req.headers.range ?? ""));
    if (!m) { res.writeHead(200); return res.end(data); }
    const start = Number(m[1]);
    const end = Math.min(Number(m[2]), data.length - 1);
    res.writeHead(206, { "Content-Range": `bytes ${start}-${end}/${data.length}`, "Content-Type": "video/x-matroska" });
    return res.end(data.subarray(start, end + 1));
  }
  if (url.pathname === "/subtitles/:/transcode/universal/start") {
    const rk = (url.searchParams.get("path") ?? "").split("/").pop()!;
    const id = selected[rk];
    const s = id ? allSubs.get(id) : undefined;
    if (!s) { res.writeHead(400); return res.end(); }
    if (s.fails) { res.writeHead(500); return res.end(); }
    const offset = Number(url.searchParams.get("offset") ?? 0);
    const read: PlexRead = { session: url.searchParams.get("session")!, id, offset, stopped: false, done: false, open: true };
    reads.push(read);
    res.on("close", () => { read.open = false; });
    const held = s.codec === "ass" && offset > 0;
    const lines = s.lines.filter((l) => l.start >= offset);
    res.writeHead(200, { "Content-Type": "application/octet-stream" });
    res.write(ASS_HEADER);
    let sent = 0;
    // What is left of the last chunk: its final byte, sent with the next, so
    // a "\r\n" now and then arrives in two.
    let tail = "";
    const began = Date.now();
    const write = (text: string) => { if (read.open) res.write(text); };
    const timer = setInterval(() => {
      const at = offset + (Date.now() - began) * PACE;
      const finished = at >= DURATION;
      if (read.stopped) {
        clearInterval(timer);
        read.done = true;
        if (read.open) res.end();
        return;
      }
      if (!held) {
        let chunk = tail;
        while (sent < lines.length && lines[sent].start <= at) chunk += plexLine(s, lines[sent++]);
        tail = finished ? "" : chunk.slice(-1);
        chunk = finished ? chunk : chunk.slice(0, -1);
        if (chunk) write(chunk);
      } else if (finished) {
        write(lines.map((l) => plexLine(s, l)).join(""));
      }
      if (finished) {
        clearInterval(timer);
        read.done = true;
        if (read.open) res.end();
      }
    }, 20);
    return;
  }
  if (url.pathname === "/video/:/transcode/universal/stop") {
    const session = url.searchParams.get("session")!;
    stops.push(session);
    const read = reads.find((r) => r.session === session);
    if (read) read.stopped = true;
    return send({});
  }
  if (url.pathname === "/video/:/transcode/universal/decision") return send({});
  res.writeHead(404);
  res.end();
});
await new Promise<void>((r) => plex.listen(0, "127.0.0.1", r));
