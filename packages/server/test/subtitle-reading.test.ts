/**
 * Subtitles inside the file, read for players as they need them.
 *
 * Against a fake Plex that reads a subtitle out of a film the way the real one
 * was measured to (scratch reads of American Honey, A Place in the Sun, Animal
 * House, Jujutsu Kaisen and Violet Evergarden, October 2026):
 *
 *  - It sends ASS with Windows line ends, one line per event and no blank line
 *    between them, a few lines at a time as it goes through the film — here at
 *    1200 film seconds a second, so a two-hour film takes six. A chunk can end
 *    between the "\r" and the "\n".
 *  - Asked to start somewhere (`offset`), it does, for a subtitle it converts
 *    (SRT, MP4's text). One it copies (ASS) it starts there too, but holds
 *    every line back until it reaches the end of the file.
 *  - Letting go of its answer doesn't stop it: it reads on until told to stop
 *    (/video/:/transcode/universal/stop) or it reaches the end.
 *
 * And Matroska files built by mkv-fixture.ts, with and without an index of
 * their subtitle lines.
 */
